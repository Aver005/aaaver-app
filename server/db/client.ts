import { SQL } from 'bun'
import { config } from '../config'

/**
 * Подключение к Postgres стека.
 *
 * Клиент встроен в Bun (`Bun.SQL`), поэтому у сервера по-прежнему ноль
 * npm-зависимостей: драйвер обновляется вместе с рантаймом, отдельно чинить
 * нечего.
 *
 * Конструктор ничего не открывает — соединение поднимается на первом запросе.
 * Это здесь не мелочь, а условие: `depends_on: postgres` в этом проекте
 * недоступен (Postgres описан в родительском `/root/compose.yml`, и ссылка на
 * него из включаемого файла ломает compose), поэтому контейнер обязан
 * подниматься при лежащей базе и отдавать статику как ни в чём не бывало.
 *
 * Инстанс переживает отказ Postgres и работает дальше после его возвращения,
 * поэтому пересоздавать его на ошибках не нужно.
 *
 * `sslmode=require` живёт в строке подключения (см. `.env.example`) и выбран
 * осознанно: в `pg_hba` стека стоит `hostssl` — шифрование обязательно, — но
 * сертификат выписан на `db.kiviuly.ru`, а ходим мы по имени контейнера `pg`,
 * и `verify-full` не прошёл бы. Трафик не покидает машину.
 */
export const sql = new SQL(config.databaseUrl, {
    // Сайт-визитка: десятка соединений хватает с запасом, а Postgres в стеке
    // один на все проекты — занимать его пул незачем.
    max: 8,
    // Без потолка запрос к лежащей базе висел бы до таймаута сокета, а вместе
    // с ним висел бы и HTTP-запрос посетителя.
    connectionTimeout: 10,
})

/**
 * Ошибка соединения, а не ошибка запроса.
 *
 * Различать обязательно: недоступный Postgres — это 503 и «попробуйте позже»,
 * а нарушенное ограничение или опечатка в SQL — это 500 и наш баг. Postgres
 * сообщает о втором кодом `ERR_POSTGRES_SERVER_ERROR`, всё остальное с этим
 * префиксом — про соединение.
 */
export function isConnectionError(error: unknown): boolean {
    const code = (error as { code?: unknown } | null)?.code
    return typeof code === 'string' && code.startsWith('ERR_POSTGRES_') && code !== 'ERR_POSTGRES_SERVER_ERROR'
}

/**
 * Нарушение уникального ключа (SQLSTATE 23505).
 *
 * Нужно там, где вставка сама по себе И ЕСТЬ проверка: «этот `jti` уже
 * предъявляли». Ловить такую вставку голым `catch` нельзя — в тот же catch
 * попадёт лежащий Postgres, и человек прочитает «этот вход уже использован»
 * вместо «база недоступна», то есть ровно противоположное правде.
 */
export function isUniqueViolation(error: unknown): boolean {
    const errno = (error as { errno?: unknown } | null)?.errno
    return String(errno) === '23505'
}
